int romanToInt(char* s) {
    // 1. 准备一个数组充当“查值表”，下标是字符的 ASCII 码
    int value[256] = {0};
    value['I'] = 1;
    value['V'] = 5;
    value['X'] = 10;
    value['L'] = 50;
    value['C'] = 100;
    value['D'] = 500;
    value['M'] = 1000;

    int result = 0;
    int i = 0;

    // 2. 遍历字符串，直到遇到结尾符 '\0'
    while (s[i] != '\0') {
        //开始一个循环，意思是“只要当前字母不是结尾符，就继续往下走”。
        int now = value[s[i]]; // 当前字母的值
        
        // 如果后面还有字母，且当前比后面小，说明是减法组合
        if (s[i + 1] != '\0' && now < value[s[i + 1]]) {
    //看看后面还有没有字母”。如果已经是最后一个字母了，后面啥也没有，就不能往下比了。
     //当前这个字母的值，是不是比它右边那个字母的值小”。
            result -= now;
 //如果上面两个条件满足了（说明遇到了像 IV、IX 这种“小在大左边”的特殊情况），那就把当前字母的值从篮子里扣掉（-= 就是减去）。
        } else {
            result += now;
        }
        i++;
    }

    return result;
}
