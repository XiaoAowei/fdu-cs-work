#include<stdio.h>

void convert_to_binary(int n, int* len, int* digit) {
/* int n：要转换的十进制正整数。

int* len：一个整型指针。用于将二进制数的位数传回给主调函数。

int* digit：一个整型指针，指向一个数组。用于将二进制的每一位存入这个数组并传回。*/
	
    if (n == 0) {
        *len = 1;
        digit[0] = 0;
        return;
    }
    /*如果输入的数是 0，它的二进制表示就是 0（1 位数）。

*len = 1;：设置位数为 1。

digit[0] = 0;：将数组的第一个元素设为 0。

return;：直接结束函数，不再执行后面的代码。*/ 
    
    int temp = n;
    *len = 0;
    /*int temp = n;：创建一个临时变量 temp，并赋值为 n。这样做是为了在后续计算中不改变原始输入 n 的值。

*len = 0;：初始化二进制位数为 0。*/
    while (temp > 0) {
        temp /= 2;
        (*len)++;
    }
    /*这是一个循环，只要 temp 大于 0，就一直执行。

temp /= 2;：将 temp 除以 2（整数除法，相当于右移一位）。

(*len)++;：每除一次，位数加 1。*/
    
    temp = n;
    int i;
  // temp = n;：将 temp 重新赋值为原始的 n，因为刚才的循环已经把 temp 变成 0 了，现在需要重新开始提取每一位。

//int i;：声明循环变量 i。
    for ( i = *len - 1; i >= 0; i--) {
        digit[i] = temp % 2;
        temp /= 2;
    }
    /*循环从 i = *len - 1 开始，一直到 i = 0 结束。这是因为二进制的高位（最左边的位）应该放在数组的前面（较小的索引）。例如，对于 5（二进制 101），我们希望 digit[0]=1, digit[1]=0, digit[2]=1。

digit[i] = temp % 2;：取 temp 除以 2 的余数（即当前最低位的二进制值），存入数组的第 i 个位置。

temp /= 2;：将 temp 除以 2，去掉刚刚处理过的最低位的数字。

举例：n = 5，len = 3。

i = 2：digit[2] = 5 % 2 = 1，temp = 5 / 2 = 2。

i = 1：digit[1] = 2 % 2 = 0，temp = 2 / 2 = 1。

i = 0：digit[0] = 1 % 2 = 1，temp = 1 / 2 = 0。

最终数组 digit 的内容为 [1, 0, 1]，正是 5 的二进制表示。*/
}
 /*(*len)++：表示对 len 指针指向的那个变量（也就是主调函数里的那个整数）进行加 1 操作。

*len++：如果不加括号，由于运算符优先级的原因，它的含义会完全不同，变成先移动指针 len 本身，再取值。

下面我为你详细拆解一下这两种写法的区别：

1. 为什么 (*len)++ 是正确的？
在这个函数里：

len 是一个指针（地址），它指向外部的一个整数变量。

*len 是解引用操作，代表“取出 len 指向的那个变量的值”。

我们想要做的是：让那个外部变量的值加 1。

加上括号后，(*len) 被强制优先计算，变成了一个普通的整数变量（左值）。然后 ++ 作用于这个整数变量，让它自增 1。这正是我们的目的。

2. 如果不加括号，*len++ 会发生什么？
在 C 语言中，运算符的优先级是：后缀 ++ > 解引用 *。

这意味着 *len++ 实际上会被编译器解析为：
*(len++)

它的执行顺序是：

先计算 len++：由于是后缀自增，表达式会先返回 len 当前的地址，然后再把指针 len 自己的内存地址向后移动（比如移动 4 个字节，
因为 int 通常占 4 字节）。

然后执行 *：对刚才返回的那个旧地址进行解引用，取出值。

结果就是：

外部那个整数的值没有变。

指针 len 被移动了，指向了未知的内存区域，这会导致严重的程序错误（野指针）。

3. 举个直观的例子
假设外部有一个变量 int length = 5;，你把这个变量的地址传给了函数，所以函数里的 len 指向 length。

写法 A（正确）：(*len)++;

取出 len 指向的值（5）。

把它加 1，变成 6。

写回内存。

结果：外部的 length 变成了 6。指针 len 没有变。

写法 B（错误）：*len++;

先返回 len 当前的地址，然后把指针 len 自己的地址加 4。

对刚才返回的旧地址解引用，取出值（5）。

这个值 5 被丢弃（因为没有赋值给任何变量）。

结果：外部的 length 仍然是 5。指针 len 变成了一个无效地址。

总结
在 C 语言中，涉及到指针的解引用和自增/自减运算符时，一定要加括号来明确你的意图：

(*ptr)++：改变指针指向的值。

*ptr++：移动指针本身（通常用于遍历数组）。

++*ptr：先对指针指向的值加 1，再取出来用（和 (*ptr)++ 在单独作为语句时效果类似，但结合其他运算时顺序不同）。*/



